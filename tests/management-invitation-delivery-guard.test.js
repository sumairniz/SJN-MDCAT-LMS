"use strict";
const {test}=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
test("Invitation delivery is never redeemable until verified and committed",()=>{
 const sql=read("database/management/isolated-staff-invitation-delivery-guard.sql");
 assert.match(sql,/delivery_status text not null default 'queued'/);
 assert.match(sql,/state<>'pending' or v_inv.delivery_status<>'sent'/);
 assert.match(sql,/mednest_staff_finalize_invitation_delivery/);
 assert.match(sql,/not public\.mednest_staff_sensitive_authorized\(p_actor,p_session,'staff\.invite'\)/);
 assert.match(sql,/delivery_status='sent'/);
 assert.match(sql,/daily_invitation_limit/);
 assert.match(sql,/revoke all on function public\.mednest_staff_finalize_invitation_delivery/);
 assert.doesNotMatch(sql,/aozknkrwafowsrehdwlr|public\.profiles|student_attempt/);
});
test("Invited recipient preview checks verified user/session and exact email BEFORE Chief role check",()=>{
 const s=read("database/management/mednest-isolated-team-actions/index.ts");
 assert.match(s,/const WRITES_ENABLED=false/);
 assert.match(s,/\["capabilities","invite\.preview"\]\.includes\(body.action\)/);
 assert.match(s,/db\.auth\.getUser\(token\)/);
 assert.match(s,/mednest_staff_session_live/);
 const preview=s.indexOf('if(body.action==="invite.preview")');
 const chief=s.indexOf('if(!isChief)return response(origin,403',preview);
 assert.ok(preview>=0&&chief>preview,"recipient preview must precede Chief-only actions");
 assert.ok(s.includes('inv.email!==(user.email||"").trim().toLowerCase()'));
 assert.match(s,/inv.delivery_status!=="sent"/);
 assert.match(s,/inv.state!=="pending"/);
 assert.match(s,/!WRITES_ENABLED\)return response/);
 assert.match(s,/mednest_staff_finalize_invitation_delivery/);
 assert.doesNotMatch(s,/update\(\{state:"revoked"/);
});
test("New invitation page is invitation-scoped and does not create accounts or change staff membership",()=>{
 const html=read("apps/management/isolated-staff-invite.html");
 const s=read("apps/management/isolated-staff-invite.js");
 assert.match(html,/noindex,nofollow,noarchive/);
 assert.match(html,/Private Staff Invitation/);
 assert.match(s,/const REGISTRATION_ENABLED=false/);
 assert.match(s,/const ACCEPTANCE_ENABLED=false/);
 assert.match(s,/storageKey:"sjn-mednest-isolated-staff-v1"/);
 assert.match(s,/client\.auth\.getUser\(\)/);
 assert.match(s,/window\.history\.replaceState\(null,"",window\.location\.pathname\)/);
 assert.match(s,/call\("invite\.preview"/);
 assert.match(s,/call\("invite\.accept"/);
 assert.doesNotMatch(s,/client\.auth\.signUp\(/);
 assert.ok(!s.includes("window.localStorage.")&&!s.includes("localStorage.setItem("));
 assert.doesNotMatch(s,/aozknkrwafowsrehdwlr/);
});
