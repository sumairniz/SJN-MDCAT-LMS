-- SJN MDCAT LMS Pro | Stage 3B-1 | REVIEW ONLY, NOT EXECUTED
-- Approved architecture, but separate owner approval required for staging SQL.
-- Target project: aozknkrwafowsrehdwlr. Never apply to production.
-- Compatible with existing /api/attempts. No attempt DML grants changed here.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
LOCK TABLE public.mcqs IN SHARE ROW EXCLUSIVE MODE;

DO $preflight$
DECLARE n integer;
BEGIN
  SELECT count(*) INTO n FROM public.mcqs;
  IF n <> 74 THEN
    RAISE EXCEPTION 'Stage 3B aborted: 74 MCQs expected, found %', n;
  END IF;
  IF (SELECT count(DISTINCT id) FROM public.mcqs) <> 74
     OR (SELECT min(id) FROM public.mcqs) <> 1
     OR (SELECT max(id) FROM public.mcqs) <> 74
     OR EXISTS (SELECT 1 FROM public.mcqs WHERE
       id NOT BETWEEN 1 AND 74
       OR bank IS DISTINCT FROM 'Past Papers Question Bank'
       OR subject IS DISTINCT FROM 'Biology'
       OR chapter IS DISTINCT FROM 'Biological Molecules'
       OR correct_index NOT BETWEEN 0 AND 3
       OR CASE WHEN jsonb_typeof(options_json) = 'array'
         THEN jsonb_array_length(options_json) <> 4 ELSE TRUE END))
  THEN
    RAISE EXCEPTION 'Stage 3B aborted: original MCQ identities/content changed';
  END IF;
END;
$preflight$;

-- One content snapshot per MCQ revision, NOT per student answer.
-- The ordinary public.mcqs question bank stays as the original content source.
CREATE TABLE public.mcq_revisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mcq_id bigint NOT NULL REFERENCES public.mcqs(id) ON DELETE RESTRICT,
  revision_no integer NOT NULL CHECK (revision_no > 0),
  bank text NOT NULL, subject text NOT NULL,
  chapter text, topic text, source text,
  question text NOT NULL, options_json jsonb NOT NULL,
  correct_index integer NOT NULL CHECK (correct_index BETWEEN 0 AND 3),
  explanation text, mnemonic text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sjn_revision_four_options CHECK
    (CASE WHEN jsonb_typeof(options_json) = 'array'
      THEN jsonb_array_length(options_json) = 4 ELSE FALSE END),
  CONSTRAINT sjn_revision_number UNIQUE (mcq_id, revision_no),
  CONSTRAINT sjn_revision_mcq_identity UNIQUE (mcq_id, id)
);

-- Historical revisions must never be edited in place.
CREATE FUNCTION public.sjn_block_revision_mutation()
RETURNS trigger LANGUAGE plpgsql SET search_path = ''
AS $block$
BEGIN
  RAISE EXCEPTION 'MCQ revisions are immutable; create a new version';
END;
$block$;
CREATE TRIGGER sjn_mcq_revisions_immutable
  BEFORE UPDATE OR DELETE ON public.mcq_revisions
  FOR EACH ROW EXECUTE FUNCTION public.sjn_block_revision_mutation();
REVOKE ALL ON FUNCTION public.sjn_block_revision_mutation()
  FROM PUBLIC, anon, authenticated;

-- Nullable current_revision_id supports future two-step MCQ publishing.
-- Only the original 74 need to have a revision in this migration.
ALTER TABLE public.mcqs ADD COLUMN current_revision_id bigint;
ALTER TABLE public.mcqs ADD CONSTRAINT sjn_mcq_current_revision_fk
  FOREIGN KEY (id, current_revision_id)
  REFERENCES public.mcq_revisions(mcq_id, id) ON DELETE RESTRICT;

INSERT INTO public.mcq_revisions (
  mcq_id, revision_no, bank, subject, chapter, topic, source,
  question, options_json, correct_index, explanation, mnemonic
)
SELECT id, 1, bank, subject, chapter, topic, source,
  question, options_json, correct_index, explanation, mnemonic
FROM public.mcqs ORDER BY id;

UPDATE public.mcqs AS m SET current_revision_id = r.id
FROM public.mcq_revisions AS r
WHERE r.mcq_id = m.id AND r.revision_no = 1;

-- details_version=0 for all existing summary-only attempts; no deletion.
ALTER TABLE public.attempts
  ADD COLUMN details_version smallint NOT NULL DEFAULT 0,
  ADD COLUMN submission_key uuid,
  ADD COLUMN submission_fingerprint text,
  ADD COLUMN elapsed_seconds integer;
ALTER TABLE public.attempts
  ADD CONSTRAINT sjn_attempt_detail_version CHECK (details_version IN (0,1)),
  ADD CONSTRAINT sjn_attempt_verified_requires_key CHECK
    (details_version = 0 OR
     (submission_key IS NOT NULL AND submission_fingerprint IS NOT NULL)),
  ADD CONSTRAINT sjn_attempt_fingerprint_hex CHECK
    (submission_fingerprint IS NULL OR
     submission_fingerprint ~ '^[0-9a-f]{64}$'),
  ADD CONSTRAINT sjn_attempt_elapsed_nonnegative CHECK
    (elapsed_seconds IS NULL OR elapsed_seconds >= 0),
  ADD CONSTRAINT sjn_attempt_key_unique UNIQUE (user_id, submission_key),
  ADD CONSTRAINT sjn_attempt_id_owner_unique UNIQUE (id, user_id);

CREATE TABLE public.attempt_items (
  attempt_id bigint NOT NULL,
  user_id uuid NOT NULL,
  position integer NOT NULL CHECK (position > 0),
  mcq_id bigint NOT NULL,
  mcq_revision_id bigint NOT NULL,
  selected_index integer CHECK (selected_index BETWEEN 0 AND 3),
  is_correct boolean NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sjn_attempt_item_pk PRIMARY KEY (attempt_id,position),
  CONSTRAINT sjn_attempt_once_per_question UNIQUE (attempt_id,mcq_id),
  CONSTRAINT sjn_attempt_skipped_not_correct
    CHECK (selected_index IS NOT NULL OR is_correct = FALSE),
  CONSTRAINT sjn_attempt_item_owner_fk
    FOREIGN KEY (attempt_id,user_id)
    REFERENCES public.attempts(id,user_id) ON DELETE CASCADE,
  CONSTRAINT sjn_attempt_item_revision_fk
    FOREIGN KEY (mcq_id,mcq_revision_id)
    REFERENCES public.mcq_revisions(mcq_id,id) ON DELETE RESTRICT
);

-- RLS and GRANT are separate controls. Students may read own saved answers;
-- nobody on anon/authenticated may directly forge item rows or revisions.
ALTER TABLE public.attempt_items ENABLE ROW LEVEL SECURITY;
CREATE POLICY sjn_attempt_items_read_own
  ON public.attempt_items FOR SELECT TO authenticated
  USING (user_id = (SELECT auth.uid()));
REVOKE ALL PRIVILEGES ON public.attempt_items FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.attempt_items TO authenticated;

-- Revision text accessible through RLS only for a student's own saved item.
-- Premium course/mock questions must NOT be put in these ordinary-bank tables.
ALTER TABLE public.mcq_revisions ENABLE ROW LEVEL SECURITY;
CREATE POLICY sjn_revisions_read_own_completed_history
  ON public.mcq_revisions FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.attempt_items ai
      WHERE ai.mcq_revision_id = public.mcq_revisions.id
        AND ai.user_id = (SELECT auth.uid())
    )
  );
REVOKE ALL PRIVILEGES ON public.mcq_revisions FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.mcq_revisions TO authenticated;

CREATE INDEX sjn_attempts_student_history_idx
  ON public.attempts (user_id, created_at DESC, id DESC);
CREATE INDEX sjn_attempt_items_student_mcq_idx
  ON public.attempt_items (user_id, mcq_id);
CREATE INDEX sjn_attempt_items_revision_owner_idx
  ON public.attempt_items (mcq_revision_id, user_id);

DO $verify$
DECLARE mismatches integer;
BEGIN
  IF (SELECT count(*) FROM public.mcq_revisions) <> 74 THEN
    RAISE EXCEPTION 'Stage 3B rollback: revision count is not 74';
  END IF;
  SELECT count(*) INTO mismatches
  FROM public.mcqs m LEFT JOIN public.mcq_revisions r
    ON r.id = m.current_revision_id AND r.mcq_id = m.id AND r.revision_no = 1
  WHERE r.id IS NULL
     OR r.bank IS DISTINCT FROM m.bank
     OR r.subject IS DISTINCT FROM m.subject
     OR r.chapter IS DISTINCT FROM m.chapter
     OR r.topic IS DISTINCT FROM m.topic
     OR r.source IS DISTINCT FROM m.source
     OR r.question IS DISTINCT FROM m.question
     OR r.options_json IS DISTINCT FROM m.options_json
     OR r.correct_index IS DISTINCT FROM m.correct_index
     OR r.explanation IS DISTINCT FROM m.explanation
     OR r.mnemonic IS DISTINCT FROM m.mnemonic;
  IF mismatches <> 0 THEN
    RAISE EXCEPTION 'Stage 3B rollback: % revision/source mismatches', mismatches;
  END IF;
  IF EXISTS (SELECT 1 FROM public.attempts WHERE details_version <> 0)
     OR EXISTS (SELECT 1 FROM public.attempt_items) THEN
    RAISE EXCEPTION 'Stage 3B rollback: unexpected historical answer writes';
  END IF;
END;
$verify$;
COMMIT;

